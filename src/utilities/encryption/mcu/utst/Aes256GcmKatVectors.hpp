/**
 * @file Aes256GcmKatVectors.hpp
 * @brief Shared AES-256-GCM known-answer vectors for equivalence testing.
 *
 * Single source of truth for the NIST vectors that pin every AES-256-GCM
 * implementation in the tree. Two suites consume this table:
 *   - src/utilities/encryption/mcu/utst/ (the shared C++ implementation)
 *   - demos/c2000_encryptor_demo/utst/  (the demo's local C implementation)
 * so a divergence in either implementation fails a host test suite even
 * though the code stays separate.
 *
 * Plain structs and arrays -- the table is data, consumable by any test
 * TU regardless of its dialect floor.
 *
 * Sources (public domain, U.S. government works):
 *   - FIPS 197, Appendix C.3 -- AES-256 block cipher example vector
 *   - NIST SP 800-38D validation set, AES-256 GCM test cases 13-16
 */

