/* --------------------- SP 800-38D GCM test cases --------------------- */

/**
 * One authenticated-encryption known-answer test case.
 *
 * pt/aad/ct are null when the corresponding length is zero. Lengths are
 * bytes. The tag is always the full 16 bytes.
 */
struct Aes256GcmKat {
  const char* name;
  uint8_t key[32];
  uint8_t nonce[12];
  const uint8_t* pt;
  uint32_t ptLen;
  const uint8_t* aad;
  uint32_t aadLen;
  const uint8_t* ct;
  uint8_t tag[16];
};

